"""Build self-hosted, subsetted web fonts for the public site.

The site used to load Noto Sans TC from Google Fonts on every page. Chinese
fonts are split into ~100 slices per weight, so a first visit downloaded
about 1 MB of font files from a third-party host before the text settled,
and every page waited on a cross-origin stylesheet.

This script collects every character used by the static pages, asks Google
Fonts for files that contain only those characters (the `text=` parameter),
and writes them to site/assets/fonts/ together with fonts.css. Characters
added later still render: the browser falls back to the system font for any
glyph missing from the subset. Re-run after large text changes:

    python scripts/build_site_fonts.py

Fonts: Noto Sans TC, Noto Serif TC and JetBrains Mono, all SIL Open Font
License 1.1.
"""
from __future__ import annotations

import pathlib
import re
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
OUT = SITE / "assets" / "fonts"
# Pages whose text should be covered. site/app/demo-data.js is a 5 MB recording
# and site/story/ is an unrelated local checkout, so both are left out.
SOURCES = [
    "index.html",
    "meeting/index.html", "meeting/meeting.js",
    "rq1/index.html", "rq1/story.js", "rq1/story-cases.json",
    "demo/index.html", "demo/cases.js",
    "app/index.html",
]
FACES = [
    # (family on Google Fonts, weight, file stem)
    ("Noto Sans TC", 400, "noto-sans-tc-400"),
    ("Noto Sans TC", 700, "noto-sans-tc-700"),
    ("Noto Serif TC", 700, "noto-serif-tc-700"),
    ("Noto Serif TC", 900, "noto-serif-tc-900"),
    ("JetBrains Mono", 400, "jetbrains-mono-400"),
    ("JetBrains Mono", 700, "jetbrains-mono-700"),
]
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
EXTRA = "，。、；：？！「」『』（）《》〈〉…·・％＋－×÷＝→←↑↓⇄⇅✕◐▶▼‹›−±≤≥≠≈°′″"
MONO = ASCII + "⇄⇅✕◐▶▼‹›−±≤≥≠≈°"
CHUNK = 600  # Google Fonts ignores `text=` once the URL passes ~7,000 characters
URL_RE = re.compile(r"url\((https://fonts\.gstatic\.com/[^)]+)\)")


def site_chars() -> str:
    chars: set[str] = set(ASCII) | set(EXTRA)
    for rel in SOURCES:
        text = (SITE / rel).read_text(encoding="utf-8")
        chars.update(c for c in text if ord(c) > 0x7F and not c.isspace())
    return "".join(sorted(chars))


def ranges(text: str) -> str:
    """CSS unicode-range covering exactly these characters, merging runs."""
    cps = sorted({ord(c) for c in text})
    out = []
    start = prev = cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        out.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
        if cp is not None:
            start = prev = cp
    return ",".join(out)


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:  # noqa: S310 (fixed https host)
        return r.read()


def main() -> int:
    chars = site_chars()
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    css = ["/* Generated by scripts/build_site_fonts.py; do not edit. SIL OFL 1.1 fonts. */"]
    total = 0
    for family, weight, stem in FACES:
        parts = [MONO] if family == "JetBrains Mono" else [chars[i:i + CHUNK] for i in range(0, len(chars), CHUNK)]
        for n, text in enumerate(parts):
            q = urllib.parse.urlencode({"family": f"{family}:wght@{weight}", "text": text, "display": "swap"})
            urls = URL_RE.findall(fetch(f"https://fonts.googleapis.com/css2?{q}").decode("utf-8"))
            if len(urls) != 1:
                print(f"{family} {weight} part {n}: expected one file, got {len(urls)}", file=sys.stderr)
                return 1
            data = fetch(urls[0])
            if not data.startswith(b"wOF2"):
                print(f"{family} {weight} part {n}: not a woff2 file", file=sys.stderr)
                return 1
            fname = f"{stem}-{n}.woff2" if len(parts) > 1 else f"{stem}.woff2"
            (OUT / fname).write_bytes(data)
            total += len(data)
            css.append(
                "@font-face{font-family:'%s';font-style:normal;font-weight:%d;font-display:swap;"
                "src:url('%s') format('woff2');unicode-range:%s}" % (family, weight, fname, ranges(text))
            )
            print(f"{fname}  {len(data) / 1024:.0f} KB")
    (OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"{len(chars)} characters, {total / 1024:.0f} KB in total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
